export const teachingService = {
    async getResponse(query: string): Promise<string> {
        const lowerQuery = query.toLowerCase();

        // Check for greetings
        if (lowerQuery.match(/hello|hi|vanakkam|வணக்கம்/)) {
            return "வணக்கம்! நான் எஜுசோஷியல் ஜியோபாட். உலகின் கண்டங்களை பற்றிச் சொல்லுங்களேன், நான் விளக்குகிறேன். (Hello! I am GeoBot. Ask me about any continent.)";
        }

        // Check for continent keywords
        for (const key in KNOWLEDGE_BASE) {
            if (lowerQuery.includes(key) || lowerQuery.includes(key.replace('_', ' '))) {
                const info = KNOWLEDGE_BASE[key];
                return `${info.name}: ${info.description} முக்கிய தகவல்கள்: ${info.facts.join(' ')}`;
            }
        }

        return "மன்னிக்கவும், எனக்கு அது புரியவில்லை. ஆசியா, ஆப்பிரிக்கா போன்ற கண்டங்களை பற்றி கேளுங்கள். (Sorry, I didn't get that. Please ask about continents like Asia, Africa, etc.)";
    }
};
